import org.mapstruct.Mapping;
import org.mapstruct.factory.Mappers;

/**
 * Domain to API view mapping, generated by MapStruct at compile time. Same-named record components map
 * implicitly; the explicit mappings flatten nested domain structure (definition, position, footprint) into views.
 */
@Mapper
public interface DesignViewMapper {
    DesignViewMapper INSTANCE = Mappers.getMapper(DesignViewMapper.class);

    SheetView sheet(Sheet sheet);

    PointView point(Point point);

    WireView wire(Wire wire);

    NetView net(Net net);

    @Mapping(target = "point", source = "at")
    NetLabelView label(NetLabel label);

    TraceView trace(Trace trace);

    PadView pad(PcbGeometry.PlacedPad pad);

    ParameterView parameter(ParameterDefinition parameter);

    PinSpec pin(PinDefinition pin);

    PadSpec pad(Pad pad);

    BodySpec body(Body body);

    SolidView solid(AssemblyBuilder.Solid solid);

    Diagnostic diagnostic(DesignValidator.Finding finding);

    Diagnostic diagnostic(BoardAnalyzer.Finding finding);

    Diagnostic diagnostic(AssemblyBuilder.Finding finding);

    @Mapping(target = "footprintName", source = "footprint.name")
    @Mapping(target = "pads", source = "footprint.pads")
    @Mapping(target = "courtyardWidthMm", source = "footprint.courtyardWidthMm")
    @Mapping(target = "courtyardHeightMm", source = "footprint.courtyardHeightMm")
    PartSpec part(Definition definition);

    @Mapping(target = "schematicReady", constant = "true")
    @Mapping(target = "pcbReady", expression = "java(definition.footprint().physical())")
    @Mapping(target = "simulationReady", constant = "true")
    DefinitionView definition(Definition definition);

    @Mapping(target = "definitionId", source = "definition.id")
    @Mapping(target = "definitionVersion", source = "definition.version")
    @Mapping(target = "name", source = "definition.name")
    @Mapping(target = "kind", source = "definition.kind")
    @Mapping(target = "xMm", source = "position.x")
    @Mapping(target = "yMm", source = "position.y")
    @Mapping(target = "parameters", source = "definition.parameters")
    @Mapping(target = "physical", expression = "java(component.definition().footprint().physical())")
    @Mapping(target = "pins", expression = "java(pins(component))")
    ComponentView component(Component component);

    /** Library definitions describe pins by number only; instance IDs exist once a component is placed. */
    default PinView pinView(PinDefinition pin) {
        return new PinView(null, pin.number(), pin.name(), pin.required());
    }

    /** Pin names come from the definition; IDs from the placed instance. */
    default List<PinView> pins(Component component) {
        return component.pins().stream().map(pin -> {
            var spec = component.definition().pins().stream().filter(d -> d.number().equals(pin.number()))
                    .findFirst().orElseThrow();
            return new PinView(pin.id(), pin.number(), spec.name(), spec.required());
        }).toList();
    }

    /** Properties are sorted so snapshots are stable regardless of edit order. */
    default Map<String, String> properties(Map<String, String> properties) {
        return new TreeMap<>(properties);
    }

    default PlacementView placement(Project project, net.talaatharb.expanse.domain.Design.Placement placement) {
        var component = project.component(placement.componentId());
        var footprint = component.definition().footprint();
        return new PlacementView(placement.componentId(), component.reference(), placement.xMm(), placement.yMm(),
                placement.rotation(), footprint.courtyardWidthMm(), footprint.courtyardHeightMm());
    }

    default Summary summary(Project project) {
        return new Summary(project.id(), project.name(), project.revision(), project.components().size(),
                project.nets().size());
    }

    default Snapshot snapshot(Project project) {
        var board = project.board();
        return new Snapshot(project.id(), project.name(), project.revision(),
                project.sheets().stream().map(this::sheet).toList(),
                project.components().stream().map(this::component).toList(),
                project.nets().stream().map(this::net).toList(),
                new BoardView(board.widthMm(), board.heightMm(), board.thicknessMm(), board.clearanceMm(),
                        board.placements().stream().map(p -> placement(project, p)).toList(),
                        board.traces().stream().map(this::trace).toList(),
                        PcbGeometry.pads(project).stream().map(this::pad).toList()),
                project.parts().stream().map(this::part).toList());
    }
}
